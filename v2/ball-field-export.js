// Builds the downloadable ES module from the same runtime source the editor runs.
function buildBallFieldModule(settings) {
  return `// Ball Field background, generated by Murmuration Lab v2.
export const ballFieldSettings = ${JSON.stringify(settings, null, 2)};
const BALL_FIELD_DEFAULTS = Object.freeze(${JSON.stringify(BALL_FIELD_DEFAULTS, null, 2)});
${createBallFieldRuntime.toString()}

export function createBallFieldBackground(el, { settings = ballFieldSettings, ...options } = {}) {
  return createBallFieldRuntime(el, { settings, ...options });
}
`;
}

function buildBallFieldSnippet(theme = 'light') {
  return `<div id="ball-field-bg"></div>
<script type="module">
  import { createBallFieldBackground } from "./ball-field-background.js";
  const field = createBallFieldBackground(document.querySelector("#ball-field-bg"), { theme: "${theme}" });
  // field.setTheme("dark"); field.pause(); field.play(); field.update({ twistAngle: 40 });
<\/script>`;
}
