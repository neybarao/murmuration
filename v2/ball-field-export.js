// Builds the downloadable ES module from the same runtime source the editor runs.
// The module carries the tuned states (home, chat, ...) and the transition duration; it has no editor UI.
function buildBallFieldModule({ states, transitionDuration = 1200 }) {
  return `// Ball Field background, generated by Murmuration Lab v2.
export const ballFieldStates = ${JSON.stringify(states, null, 2)};
export const defaultTransitionDuration = ${transitionDuration};
const BALL_FIELD_EFFECTS = ${JSON.stringify(BALL_FIELD_EFFECTS, null, 2)};
const BALL_FIELD_DEFAULTS = ${JSON.stringify(BALL_FIELD_DEFAULTS, null, 2)};
${createBallFieldRuntime.toString()}

export function createBallFieldBackground(el, {
  states = ballFieldStates,
  initialState = 'home',
  transitionDuration = defaultTransitionDuration,
  ...options
} = {}) {
  return createBallFieldRuntime(el, { states, initialState, transitionDuration, ...options });
}
`;
}

function buildBallFieldSnippet({ theme = 'light', state = 'home' } = {}) {
  return `<div id="ball-field-bg"></div>
<script type="module">
  import { createBallFieldBackground } from "./ball-field-background.js";
  const field = createBallFieldBackground(document.querySelector("#ball-field-bg"), {
    initialState: "${state}",
    theme: "${theme}"
  });
  // When the app changes screen or theme:
  // field.transitionTo("chat");
  // field.setTheme("dark");
<\/script>`;
}
